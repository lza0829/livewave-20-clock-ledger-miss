"""双钟水位线：口径权威已收归口径账本，本模块只保留双钟计算与只读视图。

设计取舍（全局只此一种，强制切换重放，见 modules/口径账本）：
- 水位线每房只有一条「权威水位」，由账本现行世代口径选定看哪只钟：
  口径=事件时 → 水位=已见最大事件时，处理时仅审计；
  口径=处理时 → 水位=已见最大处理时，事件时只做窗键对齐，不得抬水位。
- 关窗/旁路判定只读账本口径下的权威水位，任何代码路径不得拿另一钟另算关窗。
- 改钟只能走账本强制切换重放（同票作废旧世代→重放未关闭边界→新世代），
  禁止只改站规字段就换钟。行内口径戳与账本漂移即失败闭。
"""
from app.modules import 口径账本 as _账

状态 = "已实现"

口径事件时 = _账.口径事件时
口径处理时 = _账.口径处理时
口径集 = _账.口径集

旁路原因口径冲突 = _账.旁路原因口径冲突
账本冲突 = _账.账本冲突


def 全局口径(conn) -> str:
    """权威口径只采信账本现行世代；全空未选定时回退站规默认钟。"""
    return _账.全局口径(conn)


def 房口径(conn, 房间键: str) -> str:
    """本房账本口径（抬升/关窗/旁路只吃它，不回读站规）。"""
    return _账.现行口径(conn, 房间键)


def 推进候选(事件时: str, 处理时: str, 口径: str) -> str:
    """本口径下允许抬水位的那个时刻；另一只钟永远不得成为候选。"""
    return 事件时 if 口径 == 口径事件时 else 处理时


def 口径漂移(水位行, 口径: str) -> bool:
    """行内口径戳与账本口径不一致 = 切换半截/越权改库，必须失败闭。"""
    return 水位行 is not None and 水位行["口径"] != 口径


def 切换口径(conn, 新口径: str, 批号: str = "", 时刻: str | None = None):
    """强制切换重放：成功返回 (True, 消息)，硬约束冲突抛 账本冲突由上层整票回滚。"""
    from app.seed import 此刻
    果 = _账.改钟重放(conn, 新口径, 批号 or "强制切换重放", 时刻 or 此刻())
    if not 果.get("切换"):
        return True, 果["消息"]
    if 果.get("全空切换"):
        return True, f"系统全空原子切换:{果['旧口径']}→{果['新口径']}（无物可重放）"
    return True, (
        f"强制切换重放:{果['旧口径']}→{果['新口径']}，"
        f"旧世代作废、新账本世代{果['账本世代']}，未关闭边界已按新钟重放，旧关闭集冻结不回溯"
    )


def 双钟视图(conn) -> dict:
    """只读接口：每房（房间、水位[按口径为事件时或处理时水位]、口径、valid）+ 审计双钟 + 账本世代。"""
    口径 = 全局口径(conn)
    房间 = []
    for r in conn.execute(
        """SELECT w.*, l.标题, l.主播 FROM 水位线 w
           JOIN 直播间 l ON l.房间键 = w.房间键 ORDER BY w.房间键"""
    ):
        账行 = _账.现行账本行(conn, r["房间键"])
        # 已钉账：必须与账本世代一致；尚未钉账（全空默认）：与站规默认钟一致即有效。
        有效 = (r["口径"] == 口径) and (账行 is None or 账行["口径"] == r["口径"])
        房间.append(
            {
                "房间键": r["房间键"],
                "标题": r["标题"],
                "主播": r["主播"],
                "口径": r["口径"],
                "账本世代": int(账行["账本世代"]) if 账行 else 0,
                "水位": r["水位"],
                "水位钟": "事件时水位" if r["口径"] == 口径事件时 else "处理时水位",
                "有效": 有效,
                "审计事件时": r["审计事件时"] or "",
                "审计处理时": r["审计处理时"] or "",
                "允许迟到秒": r["允许迟到秒"],
                "更新处理时": r["更新处理时"],
            }
        )
    return {"全局口径": 口径, "账本钉死": _账.现行账本行(conn) is not None, "房间": 房间}
