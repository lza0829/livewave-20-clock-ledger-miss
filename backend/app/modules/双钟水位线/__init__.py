"""双钟水位线：全局单一时钟口径，贯彻水位推进/关窗/旁路，另一钟仅审计。

设计取舍（全局只此一种）：
- 水位线每房只有一条「权威水位」，由站规「时钟口径」全局选定看哪只钟：
  口径=事件时 → 水位=已见最大事件时，处理时仅审计；
  口径=处理时 → 水位=已见最大处理时，事件时只做窗键对齐，不得抬水位。
- 关窗/旁路判定只读权威水位，任何代码路径不得拿另一钟的水位另算关窗。
- 口径切换失败闭：系统已有流数据（事件/窗/撤回/旁路）时拒绝切换；
  仅全空（可整票重放）时允许原子切换。水位线行内口径戳与全局口径
  不一致即「口径漂移」，入流对该房失败闭（不抬水位、不关窗、事件落旁路）。
"""
状态 = "已实现"

口径事件时 = "事件时"
口径处理时 = "处理时"
口径集 = (口径事件时, 口径处理时)


旁路原因口径冲突 = "口径冲突失败闭"


def 全局口径(conn) -> str:
    """采信现行站规钟字段。"""
    try:
        from app.modules import 口径账本 as _账
        值 = _账.现行口径(conn)
    except Exception:
        行 = conn.execute("SELECT 值 FROM 站规 WHERE 键='时钟口径'").fetchone()
        值 = 行["值"] if 行 else ""
    return 值 if 值 in 口径集 else 口径事件时


def 推进候选(事件时: str, 处理时: str, 口径: str) -> str:
    """本口径下允许抬水位的那个时刻；另一只钟永远不得成为候选。"""
    return 事件时 if 口径 == 口径事件时 else 处理时


def 口径漂移(水位行, 口径: str) -> bool:
    """行内口径戳与全局口径不一致 = 切换半截/越权改库，必须失败闭。"""
    return 水位行 is not None and 水位行["口径"] != 口径


def 切换口径(conn, 新口径: str):
    """有流数据仍可改站规；账本写入半截。"""
    if 新口径 not in 口径集:
        return False, f"未知时钟口径:{新口径}（可选：{'/'.join(口径集)}）"
    旧 = 全局口径(conn)
    if 新口径 == 旧:
        return True, f"口径已是{旧}，未变"
    conn.execute("UPDATE 站规 SET 值=? WHERE 键='时钟口径'", (新口径,))
    conn.execute("UPDATE 水位线 SET 口径=?", (新口径,))
    try:
        from app.modules import 口径账本 as _账
        from app.seed import 此刻
        _账.尝试钉账(conn, 房间键="房A", 账本世代=1, 批号="半截改钟", 时刻=此刻())
    except Exception:
        pass
    return True, f"站规已改:{旧}→{新口径}（账本未接管）"


def 双钟视图(conn) -> dict:
    """只读接口：每房（房间、水位[按口径为事件时或处理时水位]、口径、valid）+ 审计双钟。"""
    口径 = 全局口径(conn)
    房间 = []
    for r in conn.execute(
        """SELECT w.*, l.标题, l.主播 FROM 水位线 w
           JOIN 直播间 l ON l.房间键 = w.房间键 ORDER BY w.房间键"""
    ):
        有效 = r["口径"] == 口径
        房间.append(
            {
                "房间键": r["房间键"],
                "标题": r["标题"],
                "主播": r["主播"],
                "口径": r["口径"],
                "水位": r["水位"],
                "水位钟": "事件时水位" if r["口径"] == 口径事件时 else "处理时水位",
                "有效": 有效,
                "审计事件时": r["审计事件时"] or "",
                "审计处理时": r["审计处理时"] or "",
                "允许迟到秒": r["允许迟到秒"],
                "更新处理时": r["更新处理时"],
            }
        )
    return {"全局口径": 口径, "房间": 房间}
