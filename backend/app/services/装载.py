import json
import sqlite3
from app.db import 连接
from app.seed import 此刻
from app.modules import 双钟水位线, 口径账本
from app.services import 时间, 热度窗


def 装一批(体: dict) -> dict:
    """入流一批互动事件：账本口径推进水位线，尝试关窗，处理迟到/旁路/撤回。

    口径（账本强制切换重放，见 modules/口径账本）：
    - 口径权威只在口径账本：首次选定同票钉账（房间/口径/生效水位/账本世代），
      此后抬升、关窗扫描、旁路界只吃账本现行世代口径，不回读站规。
    - 口径=事件时：水位 = 已见最大事件时；处理时仅审计
    - 口径=处理时：水位 = 已见最大处理时；事件时仅用于窗键对齐，不得抬水位
    - 窗 [起,止) 在 水位>=止 时关闭发射，关闭行盖账本世代戳
    - 关闭后至 水位>=止+允许迟到 仍可迟到修正并发撤回
    - 越过 止+允许迟到 则旁路
    - 批首切换请求走强制切换重放（整票同成败）；与关窗扫描并发冲突时重试，
      任一硬约束失败则整票回滚，绝不落半截结论。
    """
    批次编号 = 体.get("批次编号") or f"批-{此刻().replace(':', '').replace('-', '')}"
    事件列表 = 体.get("事件") or []

    末次错 = None
    for _尝试 in range(3):
        conn = 连接()
        try:
            return _装一票(conn, 批次编号, 体, 事件列表)
        except 口径账本.账本冲突 as e:
            conn.rollback()
            末次错 = e
        except sqlite3.OperationalError as e:
            # database is locked：并发改钟/关窗抢写，整票回滚后重试，禁止半票落库。
            conn.rollback()
            末次错 = e
            if "locked" not in str(e).lower():
                raise
        finally:
            conn.close()
    raise 口径账本.账本冲突(f"批次{批次编号}整票失败闭（重试耗尽）:{末次错}")


def _装一票(conn, 批次编号: str, 体: dict, 事件列表: list) -> dict:
    # 一票开头即取写锁（IMMEDIATE）：改钟与关窗扫描并发时在锁外排队，
    # 拿到锁后整票执行、整票提交，杜绝读→写升级窗口里的半截结论。
    conn.execute("BEGIN IMMEDIATE")
    全局 = 双钟水位线.全局口径(conn)
    报告 = {
        "批次编号": 批次编号,
        "口径": 全局,
        "入流": 0,
        "入窗": 0,
        "旁路": 0,
        "撤回": 0,
        "新关窗": 0,
        "明细": [],
    }

    欲切 = 体.get("尝试切换口径") or ""
    if 欲切:
        成, 消息 = 双钟水位线.切换口径(conn, 欲切, 批号=f"批首切换:{批次编号}")
        报告["口径切换"] = 消息
        if 成:
            全局 = 双钟水位线.全局口径(conn)
            报告["口径"] = 全局
        else:
            raise 口径账本.账本冲突(消息)

    站 = {r["键"]: r["值"] for r in conn.execute("SELECT 键, 值 FROM 站规")}
    窗长 = int(站.get("窗长秒", "60"))
    默许迟到 = int(站.get("允许迟到秒", "30"))

    for ev in 事件列表:
        房间键 = ev["房间键"]
        房 = conn.execute("SELECT * FROM 直播间 WHERE 房间键=?", (房间键,)).fetchone()
        if not 房:
            conn.execute(
                "INSERT INTO 旁路匣(原因, 载荷, 时刻) VALUES (?,?,?)",
                ("未知直播间", json.dumps(ev, ensure_ascii=False), 此刻()),
            )
            报告["旁路"] += 1
            报告["明细"].append({"事件编号": ev.get("事件编号"), "命运": "旁路-未知房"})
            continue

        水位 = conn.execute("SELECT * FROM 水位线 WHERE 房间键=?", (房间键,)).fetchone()
        if not 水位:
            conn.execute(
                "INSERT INTO 水位线(房间键, 口径, 水位, 审计事件时, 审计处理时, 允许迟到秒, 更新处理时) VALUES (?,?,?,?,?,?,?)",
                (房间键, 全局, 房["开播事件时"], "", "", 默许迟到, 此刻()),
            )
            水位 = conn.execute("SELECT * FROM 水位线 WHERE 房间键=?", (房间键,)).fetchone()

        # 账本接管：首次选定同票钉账，房口径只认账本现行世代。
        世代 = 口径账本.确保房账本(
            conn, 房间键, 全局, 水位["水位"], 批号=f"首次钉账:{批次编号}", 时刻=此刻()
        )
        房口径 = 口径账本.现行口径(conn, 房间键)
        if 房口径 != 全局:
            raise 口径账本.账本冲突(
                f"房{房间键}账本口径={房口径} 与全局账本口径={全局} 并存，禁止两套钟混批"
            )

        允许迟到 = int(水位["允许迟到秒"])
        事件时 = ev["事件时"]
        处理时 = ev.get("处理时") or 此刻()
        事件编号 = ev["事件编号"]
        点赞 = int(ev.get("点赞增量") or 0)
        送礼 = int(ev.get("送礼额") or 0)
        类型 = ev.get("事件类型") or "点赞"

        if conn.execute("SELECT 1 FROM 互动事件 WHERE 事件编号=?", (事件编号,)).fetchone():
            报告["明细"].append({"事件编号": 事件编号, "命运": "幂等跳过"})
            continue

        if 双钟水位线.口径漂移(水位, 房口径):
            conn.execute(
                """INSERT INTO 互动事件(事件编号,房间键,事件类型,事件时,处理时,观众键,点赞增量,送礼额,命运,窗键,批次编号)
                   VALUES (?,?,?,?,?,?,?,?,?,?,?)""",
                (
                    事件编号, 房间键, 类型, 事件时, 处理时,
                    ev.get("观众键") or "", 点赞, 送礼, "已旁路", "", 批次编号,
                ),
            )
            conn.execute(
                "INSERT INTO 旁路匣(原因, 载荷, 时刻) VALUES (?,?,?)",
                (
                    双钟水位线.旁路原因口径冲突,
                    json.dumps(
                        {
                            "事件编号": 事件编号,
                            "房间口径戳": 水位["口径"],
                            "账本口径": 房口径,
                            "账本世代": 世代,
                            "说明": "口径漂移失败闭：本房不抬水位不关窗，待整票重放",
                        },
                        ensure_ascii=False,
                    ),
                    处理时,
                ),
            )
            报告["旁路"] += 1
            报告["明细"].append(
                {"事件编号": 事件编号, "命运": "失败闭-口径冲突", "房间口径戳": 水位["口径"], "账本口径": 房口径}
            )
            continue

        当前水位 = 水位["水位"]
        候选 = 双钟水位线.推进候选(事件时, 处理时, 房口径)
        if 时间.解析(候选) > 时间.解析(当前水位):
            当前水位 = 候选
        审计事件时 = 水位["审计事件时"]
        if not 审计事件时 or 时间.解析(事件时) > 时间.解析(审计事件时):
            审计事件时 = 事件时
        审计处理时 = 水位["审计处理时"]
        if not 审计处理时 or 时间.解析(处理时) > 时间.解析(审计处理时):
            审计处理时 = 处理时
        conn.execute(
            "UPDATE 水位线 SET 水位=?, 审计事件时=?, 审计处理时=?, 更新处理时=? WHERE 房间键=?",
            (当前水位, 审计事件时, 审计处理时, 处理时, 房间键),
        )
        # 水位写闸与账本同步：生效水位随权威水位推进，世代不变。
        conn.execute(
            "UPDATE 口径账本 SET 生效水位=? WHERE 房间键=? AND 账本世代=? AND 状态=?",
            (当前水位, 房间键, 世代, 口径账本.账本现行),
        )
        报告["新关窗"] += 热度窗.尝试关窗(
            conn, 房间键, 当前水位, 允许迟到, 窗长, 处理时, 账本世代=世代
        )

        窗起 = 时间.对齐窗起(事件时, 窗长)
        窗止 = 时间.加秒(窗起, 窗长)
        wk = 时间.窗键(房间键, 窗起)

        if 热度窗.已过旁路界(当前水位, 窗止, 允许迟到):
            conn.execute(
                """INSERT INTO 互动事件(事件编号,房间键,事件类型,事件时,处理时,观众键,点赞增量,送礼额,命运,窗键,批次编号)
                   VALUES (?,?,?,?,?,?,?,?,?,?,?)""",
                (
                    事件编号, 房间键, 类型, 事件时, 处理时,
                    ev.get("观众键") or "", 点赞, 送礼, "已旁路", "", 批次编号,
                ),
            )
            conn.execute(
                "INSERT INTO 旁路匣(原因, 载荷, 时刻) VALUES (?,?,?)",
                (
                    "超允许迟到",
                    json.dumps(
                        {
                            "事件编号": 事件编号,
                            "事件时": 事件时,
                            "窗止": 窗止,
                            "旁路界": 时间.加秒(窗止, 允许迟到),
                            "水位": 当前水位,
                            "口径": 房口径,
                            "账本世代": 世代,
                        },
                        ensure_ascii=False,
                    ),
                    处理时,
                ),
            )
            报告["旁路"] += 1
            报告["明细"].append({"事件编号": 事件编号, "命运": "已旁路", "窗键本应": wk})
            continue

        窗 = conn.execute("SELECT * FROM 热度窗 WHERE 窗键=?", (wk,)).fetchone()
        if not 窗:
            conn.execute(
                """INSERT INTO 热度窗(窗键,房间键,窗起事件时,窗止事件时,状态,点赞合计,送礼合计,事件笔数,版本,账本世代)
                   VALUES (?,?,?,?, '开启', 0, 0, 0, 0, ?)""",
                (wk, 房间键, 窗起, 窗止, 世代),
            )
            窗 = conn.execute("SELECT * FROM 热度窗 WHERE 窗键=?", (wk,)).fetchone()
            if 时间.解析(当前水位) >= 时间.解析(窗止):
                报告["新关窗"] += 热度窗.尝试关窗(
                    conn, 房间键, 当前水位, 允许迟到, 窗长, 处理时, 账本世代=世代
                )
                窗 = conn.execute("SELECT * FROM 热度窗 WHERE 窗键=?", (wk,)).fetchone()

        if 窗["状态"] == "已关闭":
            旧赞, 旧送 = 窗["点赞合计"], 窗["送礼合计"]
            新赞, 新送 = 旧赞 + 点赞, 旧送 + 送礼
            新版本 = int(窗["版本"]) + 1
            conn.execute(
                """UPDATE 热度窗 SET 点赞合计=?, 送礼合计=?, 事件笔数=事件笔数+1, 版本=? WHERE 窗键=?""",
                (新赞, 新送, 新版本, wk),
            )
            conn.execute(
                """INSERT INTO 撤回单(窗键,房间键,原因,旧点赞,新点赞,旧送礼,新送礼,处理时,事件编号)
                   VALUES (?,?,?,?,?,?,?,?,?)""",
                (wk, 房间键, "迟到修正", 旧赞, 新赞, 旧送, 新送, 处理时, 事件编号),
            )
            conn.execute(
                """INSERT INTO 互动事件(事件编号,房间键,事件类型,事件时,处理时,观众键,点赞增量,送礼额,命运,窗键,批次编号)
                   VALUES (?,?,?,?,?,?,?,?,?,?,?)""",
                (
                    事件编号, 房间键, 类型, 事件时, 处理时,
                    ev.get("观众键") or "", 点赞, 送礼, "已入窗", wk, 批次编号,
                ),
            )
            报告["入窗"] += 1
            报告["撤回"] += 1
            报告["入流"] += 1
            报告["明细"].append({"事件编号": 事件编号, "命运": "迟到修正撤回", "窗键": wk})
        else:
            conn.execute(
                """UPDATE 热度窗 SET 点赞合计=点赞合计+?, 送礼合计=送礼合计+?, 事件笔数=事件笔数+1 WHERE 窗键=?""",
                (点赞, 送礼, wk),
            )
            conn.execute(
                """INSERT INTO 互动事件(事件编号,房间键,事件类型,事件时,处理时,观众键,点赞增量,送礼额,命运,窗键,批次编号)
                   VALUES (?,?,?,?,?,?,?,?,?,?,?)""",
                (
                    事件编号, 房间键, 类型, 事件时, 处理时,
                    ev.get("观众键") or "", 点赞, 送礼, "已入窗", wk, 批次编号,
                ),
            )
            报告["入窗"] += 1
            报告["入流"] += 1
            报告["明细"].append({"事件编号": 事件编号, "命运": "已入窗", "窗键": wk})

    # 批尾关窗扫描：逐房只吃账本现行世代，漂移房跳过（失败闭），关闭行盖同世代戳。
    for 房行 in conn.execute("SELECT 房间键, 口径, 水位, 允许迟到秒 FROM 水位线"):
        账行 = 口径账本.现行账本行(conn, 房行["房间键"])
        if not 账行:
            continue
        if 房行["口径"] != 账行["口径"]:
            continue
        报告["新关窗"] += 热度窗.尝试关窗(
            conn, 房行["房间键"], 房行["水位"], int(房行["允许迟到秒"]), 窗长, 此刻(),
            账本世代=int(账行["账本世代"]),
        )

    conn.execute(
        "INSERT INTO 装载批次(编号, 时刻, 报告) VALUES (?,?,?)",
        (批次编号, 此刻(), json.dumps(报告, ensure_ascii=False)),
    )
    conn.commit()
    return 报告
